inline void drawSdlText(SDL_Renderer* r, int x, int y, const std::string& text, SDL_Color c, int scale = 3) {
    SDL_SetRenderDrawColor(r, c.r, c.g, c.b, c.a);
    int cx = x;
    for (unsigned char ch : text) {
        if (ch == '\n') {
            y += 8 * scale;
            cx = x;
            continue;
        }
        const int idx = (ch < 32 || ch > 127) ? 0 : (ch - 32);
        const uint8_t* g = kLauncherFont[idx];
        for (int row = 0; row < 7; ++row) {
            for (int col = 0; col < 5; ++col) {
                if (g[row] & (16 >> col)) {
                    SDL_Rect px{cx + col * scale, y + row * scale, scale, scale};
                    SDL_RenderFillRect(r, &px);
                }
            }
        }
        cx += 6 * scale;
    }
}

inline int sdlTextWidth(const std::string& text, int scale = 3) {
    return static_cast<int>(text.size()) * 6 * scale;
}

